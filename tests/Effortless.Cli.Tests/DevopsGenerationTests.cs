    private static JsonDocument LoadRulebook()
    {
        return JsonDocument.Parse(
            File.ReadAllText(
                Path.Combine(
                    RepositoryRoot,
                    "effortless-rulebook",
                    "effortless-rulebook.json")));
    }

    private static IReadOnlyList<ManifestEntry> LoadManifest(string relativePath)
    {
        return JsonSerializer.Deserialize<List<ManifestEntry>>(
                   File.ReadAllText(Path.Combine(RepositoryRoot, relativePath)),
                   new JsonSerializerOptions
                   {
                       PropertyNameCaseInsensitive = true,
                   })
               ?? throw new InvalidOperationException(
                   $"Could not parse generated manifest '{relativePath}'.");
    }

    private static async Task<ProcessResult> RunNode(
        string script,
        params string[] arguments)
    {
        return await RunProcess(
            "node",
            RepositoryRoot,
            [script, .. arguments]);
    }

    private static async Task<ProcessResult> RunProcess(
        string executable,
        string workingDirectory,
        params string[] arguments)
    {
        using var process = new Process
        {
            StartInfo = new ProcessStartInfo(executable)
            {
                WorkingDirectory = workingDirectory,
                RedirectStandardOutput = true,
                RedirectStandardError = true,
                UseShellExecute = false,
            },
        };
        foreach (var argument in arguments)
        {
            process.StartInfo.ArgumentList.Add(argument);
        }

        if (!process.Start())
        {
            throw new InvalidOperationException(
                $"Could not start '{executable}'.");
        }

        var standardOutput = process.StandardOutput.ReadToEndAsync();
        var standardError = process.StandardError.ReadToEndAsync();
        await process.WaitForExitAsync();

        return new ProcessResult(
            process.ExitCode,
            await standardOutput,
            await standardError);
    }

    private static string RepositoryRoot
    {
        get
        {
            var directory = new DirectoryInfo(AppContext.BaseDirectory);
            while (directory is not null)
            {
                if (File.Exists(
                        Path.Combine(
                            directory.FullName,
                            "effortless-rulebook",
                            "effortless-rulebook.json")))
                {
                    return directory.FullName;
                }

                directory = directory.Parent;
            }

            throw new DirectoryNotFoundException(
                "Could not locate the effortless-cli repository root.");
        }
    }

    private sealed record ManifestEntry(
        string Id,
        string Suite,
        string Priority,
        string Status,
        bool Slow,
        bool Interactive);

    private sealed record ProcessResult(
        int ExitCode,
        string StandardOutput,
        string StandardError);
}
