    }

    [Fact(DisplayName = "devops-coverage-gate: every retained option has a test")]
    public void EveryRetainedOptionHasATest()
    {
        using var rulebook = LoadRulebook();
        var root = rulebook.RootElement;
        var retainedDispositions = root.GetProperty("Dispositions")
            .GetProperty("data")
            .EnumerateArray()
            .Where(row => row.GetProperty("IsRetained").GetBoolean())
            .Select(row => row.GetProperty("DispositionId").GetString()!)
            .ToHashSet(StringComparer.Ordinal);
        var testCounts = root.GetProperty("TestCases")
            .GetProperty("data")
            .EnumerateArray()
            .GroupBy(row => row.GetProperty("PrimaryOption").GetString()!)
            .ToDictionary(group => group.Key, group => group.Count(), StringComparer.Ordinal);
        var untested = root.GetProperty("CliOptions")
            .GetProperty("data")
            .EnumerateArray()
            .Where(row =>
                retainedDispositions.Contains(
                    row.GetProperty("Disposition").GetString()!))
            .Select(row => row.GetProperty("CliOptionId").GetString()!)
            .Where(option => !testCounts.TryGetValue(option, out var count) || count == 0)
            .Order(StringComparer.Ordinal)
            .ToArray();

        Assert.True(
            untested.Length == 0,
            $"Retained options without test cases:{Environment.NewLine}{string.Join(Environment.NewLine, untested)}");
    }

    // HelpCommand renders "  {Flag,-26} {HelpSummary}", so a summary must fit
    // 80 - 2 - 26 - 1 columns for -help to stay inside an 80-column terminal
    // (meta-help-width). Enforced here so an over-long summary fails at
    // authoring time rather than only in the E2E golden.
    private const int MaxHelpSummaryLength = 51;

    [Fact(DisplayName = "help-summary-width: every HelpSummary fits the -help column budget")]
    public void EveryRetainedOptionHasAHelpSummaryUnder72Columns()
    {
        using var rulebook = JsonDocument.Parse(
            File.ReadAllText(
                Path.Combine(
                    RepositoryRoot,
                    "effortless-rulebook",
                    "effortless-rulebook.json")));
        var root = rulebook.RootElement;
        var retained = root.GetProperty("Dispositions").GetProperty("data")
            .EnumerateArray()
            .ToDictionary(
                row => row.GetProperty("DispositionId").GetString()!,
                row => row.GetProperty("IsRetained").GetBoolean(),
                StringComparer.Ordinal);

        var problems = new List<string>();
        foreach (var option in root.GetProperty("CliOptions").GetProperty("data")
                     .EnumerateArray()
                     .Where(row =>
                         retained[row.GetProperty("Disposition").GetString()!]))
        {
            var id = option.GetProperty("CliOptionId").GetString()!;
            var summary =
                option.TryGetProperty("HelpSummary", out var value)
                && value.ValueKind == JsonValueKind.String
                    ? value.GetString()!
                    : string.Empty;
            if (string.IsNullOrWhiteSpace(summary))
            {
                problems.Add($"{id}: HelpSummary is empty");
            }
            else if (summary.Length > MaxHelpSummaryLength)
            {
                problems.Add(
                    $"{id}: HelpSummary is {summary.Length} chars (max {MaxHelpSummaryLength})");
            }
        }

        Assert.True(
            problems.Count == 0,
            string.Join(Environment.NewLine, problems));
    }

    [Fact(DisplayName = "readme-commands-block-matches-rulebook: README block is generated")]
